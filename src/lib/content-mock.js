let hookCounter = 1000;

export function generateHookBatch(seed = 0) {
  // Devuelve una lista pseudoaleatoria del pool con id único.
  const shuffled = [...HOOK_POOL]
    .map((hook, index) => ({ ...hook, _order: (index + seed) % HOOK_POOL.length }))
    .sort((a, b) => a._order - b._order)
    .slice(0, 8);

  return shuffled.map((hook) => {
    hookCounter += 1;
    return {
      id: `HK-${hookCounter}`,
      ...hook,
    };
  });
}
